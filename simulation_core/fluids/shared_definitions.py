def _scalar_value(value):
    return struct.unpack('<d', struct.pack('<Q', int(value)))[0]


# FastFsi: verbatim from simulation_core/coupling/hibm_mpm/gpu_marker_tail.py lines 237-242
#          (source sha256 ac7eeefd474e6db5facc57cac9f60cb2353e1a511311529e76361bc0053b70f9)
def _scalar_workspace(size, stage):
    # Scalar selection does not introduce an owning work scope or extra work
    # charge: fluid CG's original caller need not own a marker host budget.
    # Preserve the original complete allocator-cap failure witness if needed.
    if size > LIMIT:
        check_workspace(size, LIMIT, stage)


# FastFsi: verbatim from simulation_core/coupling/hibm_mpm/gpu_marker_tail.py lines 245-249
#          (source sha256 ac7eeefd474e6db5facc57cac9f60cb2353e1a511311529e76361bc0053b70f9)
def scalar_maximum(first, second, *, retained_bytes=0):
    _scalar_workspace(int(retained_bytes) + 16, 'device_original_scalar_maximum')
    output = ti.ndarray(ti.u64, shape=1)
    tail_kernels().select_scalar(_scalar_raw(first), _scalar_raw(second), 0, output)
    return _scalar_value(output.to_numpy()[0])


