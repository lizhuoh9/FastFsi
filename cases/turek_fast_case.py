    # (CP300 A/B: growth +29.7 1/s -> decay -5.9 1/s, tip-force phase vs
    # velocity -53 deg -> -83 deg). False keeps the legacy sampling.
    one_sided_pressure_sampling_excludes_ib_envelope: bool = False
    # One-sided wall pressure from a linear fit over rungs 4-7 cells out (A29,
