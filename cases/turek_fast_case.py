@dataclass(frozen=True)
class TurekHronFsiConfig:
    channel_length_m: float = 2.5
    channel_height_m: float = 0.41
    span_m: float = 0.05
    cylinder_center_x_m: float = 0.2
    cylinder_center_y_m: float = 0.2
    cylinder_radius_m: float = 0.05
    beam_length_m: float = 0.35
    beam_thickness_m: float = 0.02
    beam_tip_x_m: float = 0.6
    mean_inlet_velocity_mps: float = 0.2
    inlet_ramp_time_s: float = 2.0
    fluid_density_kgm3: float = 1000.0
    fluid_viscosity_pa_s: float = 1.0
    solid_density_kgm3: float = 1000.0
    young_modulus_pa: float = 1.4e6
    poisson_ratio: float = 0.4
    # Damping ratio zeta_N prescribed for a solid mode at the macro-step
    # Nyquist frequency f_N = 1/(2 dt_s) (2026-09-15). The coupling (load held
    # over the step, end-point velocity BC) pumps the beam axial mode sitting
    # at f_N: at dt=1e-3 s the 5th axial mode (~514 Hz, nodes measured at
    # s=0.22/0.45/0.67/0.90 = 2k/9) grew 10-20 % per step and broke the
    # coupling at step 119. The Kelvin-Voigt viscosity is derived,
    # eta = 2*zeta_N*E*dt_s/pi (see solid_viscous_damping_pa_s), so a mode at
    # physical frequency f sees zeta(f) = 2*zeta_N*f*dt_s: first order in dt,
    # like an implicit integrator's dissipation, and identical across cases.
    # zeta_N=0.056 reproduces eta=200 Pa s for FSI3 (0.06 % at 5.3 Hz).
    # 0 keeps the undamped Turek-Hron solid.
    solid_nyquist_damping_ratio: float = 0.0
    # FLIP share of the MPM grid-to-particle velocity transfer (0 = pure APIC).
    # APIC loses a fixed energy fraction per transfer, so its damping grows with
    # the substep count (2026-09-29, free FSI2 beam, mode 2, h0 grid:
    # zeta = 0.81 / 1.77 / 6.8 % at 10 / 25 / 100 substeps per 1 ms step;
    # 0.64 % with 0.95 at 100 substeps). 0 keeps the legacy transfer.
    solid_velocity_transfer_flip_blend: float = 0.0
    # IB node-search wet-surface rule, in fluid cells (0 = legacy reset).  A
    # cell the particle raster calls wet but whose centre lies at most this far
    # inside the nearest marker face becomes an external IB node of that face.
    # Without it a cell released by the raster while still 0.08 mm inside the
    # marker polyline became a sealed pressure pocket (FSI2 a2 step 11705).
    ib_wet_surface_tolerance_cells: float = 0.0
    # IB tip-corner vertices (default off = three disconnected open polylines).
    # A projection-only vertex at each beam-tip corner joins the bottom/top
    # face polylines to the tip face.  With the tip rotated 20-30 deg, cells in
    # the corner shadow lay beyond both faces' endpoint extensions, their faces
    # were authored by nodes of different faces with contradictory targets and
    # the tip was kicked by 200 kPa corner pressures (FSI2 a6/b3).
    ib_tip_corner_vertices: bool = False
    # Quadratic wall-normal reconstruction (default off = linear).  Hard MAC
    # targets scale the relative wall-normal velocity by alpha^2 (alpha =
    # d_face / d_sample; faces behind the wall stay linear) and the
    # pressure-Neumann trace adds back half of the normal Taylor term.  Linear reconstruction made the raster faces 2 mm outside
    # the rigid FSI1 beam carry 3-8x the body-fitted normal velocity, an
    # along-beam leak of 1e-4 m^2/s (2026-10-01).  A stretching wall's normal
    # slope -div_s V enters both (per IB node, from its projection segment).
    ib_quadratic_normal_reconstruction: bool = False
    # Laminar viscous exchange across a canonical hard face between two fluid
    # cells (default off = legacy wall at half a cell with the hard row's
    # target).  The legacy rule gave a manufactured affine field a nonzero
    # Laplacian (0.23 / -0.51 m/s^2 at the FSI1 beam, 2026-10-01).
    fluid_laminar_canonical_patch_exchange: bool = False
    # Incremental pressure-Neumann target (default off = full target
    # rho (T_n u* - V.n) / dt).  The full target turns the persistent trace bias
    # of the accepted field into a rho/dt pressure error; the incremental target
    # keeps the predictor acceleration and the wall-velocity change only (frozen
    # FSI1 lambda 0.75 EB 2.66 -> -0.23 mm, reference -0.20; 2026-10-01).
    ib_incremental_neumann_target: bool = False
    solid_constitutive_model: str = "saint_venant_kirchhoff"
    dt_s: float = 5.0e-3
    step_count: int = 200
    grid_nodes: tuple[int, int, int] = (4, 48, 288)
    solid_particle_counts: tuple[int, int, int] = (1, 8, 140)
    # Positive int = explicit count (default 48/4). "auto" =
    # grid-adaptive: ceil(face_length / (0.75 * face-tangential cell size)),
    # guaranteeing >= 1 marker per surface cell with 25% margin at ANY grid,
    # so refining the grid can never reopen the porous-interface gap that the
    # 2026-07-09 diagnosis traced to this grid-independent default.
    markers_per_side: int | str = 48
    markers_per_tip: int | str = 4
    # 2026-09-18 A18 fix: target marker spacing for markers_per_side/tip="auto", in
    # face-tangential cell widths. 0.75 (legacy) produced sub-cell alternating
    # force modes (interface checkerboard) on L0; 1.0 removes them with no
    # measurable accuracy change (FSI2 m40 vs 54-marker lineage, 2026-09-18).
    marker_spacing_cells: float = 1.0
    solid_substeps: int = 200
    flow_predictor_substeps: int = 1
    # The 2.5 m channel spans 288 streamwise cells at the default grid; the
    # FV-CG iteration budget must scale with the domain length (the 64-cell
    # vertical-flap case needs 1080).
    flow_projection_iterations: int = 4000
    flow_pressure_solver: str = "fv_cg"
    flow_cg_tolerance: float = 1.0e-6
    # Marker-MAC Q/P transaction controls. These are frozen into component
    # evidence so terminal no-slip health is reproducible source-to-run.
    flow_hibm_marker_mac_constraint_iterations: int = 64
    flow_hibm_marker_mac_constraint_absolute_tolerance_mps: float = 1.0e-4
    # Dense pressure-nullspace factor cap (2026-09-17, default 512 = legacy):
    # marker systems with more constraint rows fall back to the sparse projector
    # whose device apply is serialized (m0: 669 rows -> 64 ms per PCG iteration).
    # Raising the cap keeps the parallel dense factor; only the backend changes.
    flow_hibm_pressure_nullspace_dense_max_constraints: int = 512
    # Scale-aware nullspace candidate audit (2026-09-17, default 0.0 = legacy
    # absolute audit): a positive ratio r accepts per-apply residuals up to
    # max(absolute tolerance, r * max|input|) - the projector acts on FV-CG
    # search directions of arbitrary magnitude, so the absolute bound alone
    # fires on f64 roundoff (m0/FSI3 probes: residual/input <= 4.4e-9).
    flow_hibm_marker_mac_constraint_relative_audit: float = 1.0e-6  # R1 2026-09-19 default
    # ulp-based form of the two f32 velocity-residual audits (A3 terminal no-slip
    # component, A20 final f32 candidate): k float32 quanta of the largest sampled
    # magnitude, default 0.0 = legacy absolute audit.
    flow_hibm_marker_mac_constraint_ulp_audit: float = 32.0  # R1 2026-09-19 default
    # A3b: terminal no-slip component gate floor in m/s (the runner sets it to a
    # fraction of the acceptance-certified absolute coupling tolerance); 0.0 = legacy.
    flow_hibm_terminal_no_slip_tolerance_mps: float = 1.0e-4  # R1 2026-09-19 default
    # A4b: certified cap (m/s) of the scale-aware pressure-nullspace audit's
    # relative term; 0.0 = legacy uncapped (the runner passes the acceptance
    # coupling_absolute_residual_mps_max).
    # A4b cap must stay STRICTLY above flow_hibm_terminal_no_slip_tolerance_mps (1e-4): at equal values
    # min(ratio*input, cap) can never beat the absolute floor and the scale-aware branch is dead code
    # (job 500, 2026-09-21: rejected a residual 1.2e5x below f32 roundoff).
    flow_hibm_pressure_nullspace_relative_audit_cap_mps: float = 1.0e-3  # R1 2026-09-19 default
    # A15 (2026-09-19): certify relocation merges whose winner/loser actual sample
    # velocities agree within this many m/s (counted); 0.0 = legacy fail-closed raise.
    ledger_relocation_merge_velocity_tolerance_mps: float = 0.0
    ledger_relocation_merge_velocity_tolerance_rel: float = 0.25  # R1 2026-09-19 default
    # CG preconditioner. Default "auto" -> Jacobi on a uniform grid. Set
    # "fv_multigrid" to force the multigrid preconditioner (converges the
    # near-obstacle deficient-stencil modes the plain CG leaves under-resolved).
    flow_cg_preconditioner: str = "auto"
    # Performance knob (2026-09-15 audit, default off = legacy behaviour):
    # seed every fluid.project() CG solve from the converged pressure of the
    # same solve slot in the previous trial/step (the stash survives the
    # trial restore, so scoping is cross-trial and cross-step).  Only the CG
    # initial guess changes; the tolerance-based exit and the accepted
    # fields are unchanged up to the solver tolerance.
    flow_pressure_warm_start: bool = False
    # Multigrid semi-coarsening (2026-09-17, default off = legacy 2-level hierarchy on
    # thin spanwise grids): halve only axes with >= 4 cells so the PCG preconditioner
    # gets a real V-cycle (L0: 2 -> 8 levels, m0: 2 -> 9).  Only the preconditioner
    # changes; the CG tolerance-based exit and the accepted fields are unchanged up
    # to the solver tolerance.
    flow_multigrid_semi_coarsening: bool = False
    # Quasi-2D repair (2026-09-16, default off = legacy point-marker constraint):
    # replicate every marker-MAC constraint donor uniformly over all spanwise
    # planes so the no-slip constraint acts identically in every x plane.  The
    # legacy 2x2x2 trilinear support reaches only the two planes nearest to
    # the mid-span marker line and leaves the outer planes unconstrained at the
    # flap tip (spanwise pressure jumps of 60-130 Pa, u_x ~ 3e-2 m/s).
    marker_constraint_spanwise_uniform: bool = False
    # Quasi-2D fluid filter (default off): zero the spanwise (x) velocity after
    # every predictor step and pressure projection.  Between two symmetry
    # planes with a plane-strain solid the exact solution has u_x = 0; keeping
    # it exactly zero makes every interior-interpolated x-face Dirichlet
    # target exactly zero (no pair-arbitration conflicts from spanwise noise).
    fluid_quasi_2d_x: bool = False
    ledger_corner_reconstruction_fallback: bool = False
    # Arm the existing extended pressure probe for one-sided markers with the
    # same thickness-derived reach the two-sided markers already use, so a tip
    # marker whose immediate fluid side is occluded can still be sampled.
    stress_one_sided_extended_probe: bool = False
    # A1 (2026-09-18, default off = legacy): a one-sided-region marker whose
    # fluid-side probe ladder finds no sample (deflected beam tip) is served by the
    # base pressure at the marker instead of failing the load transaction; counted
    # (one_sided_missing_side_fallback_marker_count).
    stress_one_sided_missing_side_fallback: bool = True  # R1 2026-09-19 default
    # Re-projection solve budget (perf, 2026-07): the dirichlet-consistency
    # and post-solid re-projections correct a tiny (~1% of total) pressure
    # increment left after the main solve, yet CG's relative tolerance is
    # scale-invariant, so with inherited settings they burn the SAME
    # iteration budget as the main solve for a physically negligible
    # correction. Production values below are the measured A/B winner
    # (th_perf_ab.py V1, 2026-07-05): 27.94 -> 16.20 s/step (1.72x) with
    # accuracy guards passing (total drag delta 0.08%, tip_uy delta 0.2%,
    # re-projection iters 4009->1229 / 2922->868). Tolerances are numerics,
    # not physics: a 1e-4 relative solve of a ~1% increment perturbs the
    # accumulated pressure by ~1e-6 relative. Set either to None to inherit
    # flow_projection_iterations/flow_cg_tolerance (legacy behavior).
    flow_reprojection_iterations: int | None = 1200
    flow_reprojection_cg_tolerance: float | None = 1.0e-4
    fluid_advection_scheme: str = "rk2"
    # A sharp boundary lies between Cartesian cell centres.  The active IB row
    # therefore needs the linearly reconstructed value between the prescribed
    # wall velocity and an interior-fluid sample; stamping the wall velocity
    # directly at the cell centre moves the effective wall by O(h) and leaves a
    # large marker-sampled slip.  Keep the core's physically consistent default
    # explicit in this benchmark so the formal certificate cannot silently use
    # the old boundary-velocity-only shortcut.
    interpolate_velocity_dirichlet_with_interior: bool = True
    # Interface velocity exchanged with the fluid (2026-09-15). "instantaneous"
    # (legacy) uses the solid's end-of-step marker velocity; a solid mode at
    # the macro-step Nyquist frequency then reverses sign every step while the
    # solid barely moves, and the fluid's added-mass pressure on that
    # non-displacing wall pumps the mode (5th axial mode, dt=1e-3, broke the
    # coupling at step 119). "step_average" exchanges the marker displacement
    # over the macro step divided by dt_s: v*dt equals the solid's actual
    # displacement, interface work is discretely consistent, and a Nyquist
    # mode receives no fluid forcing. Needs the compensated particle position
    # residual, which the MPM solid keeps for its step base and current state.
    interface_velocity_mode: str = "instantaneous"
    velocity_damping: float = 1.0
    enforce_plane_strain_x: bool = True
    surface_transfer_method: str = "cartesian_reference_adjoint_v1"
    mpm_support_radius_m: float | None = None
    # Marker-velocity coupling controls consumed by the sole generic FSI
    # runtime. Every physical step and every interface trial follows that path.
    fsi_coupling_iterations: int = 16
    # Performance knob (default off = legacy behaviour): let IQN-ILS start a
    # step from the previous step's secant history (generic driver support,
    # layout-identity checked).  Trial acceptance rules and tolerances are
    # unchanged; only the number of trials needed to reach them changes.
    fsi_iqn_reuse_previous_step_history: bool = False
    fsi_coupling_tolerance: float = 1.0e-3
    fsi_coupling_initial_relaxation: float = 0.3  # R1 2026-09-19 default
    # Absolute interface-velocity convergence floor (2026-07-10). The Picard
    # residual is RELATIVE (||dv|| / ||v_new||); during the inlet ramp the
    # interface velocities are ~0, so the relative residual is noise/noise and
    # never reaches the tolerance -- every early step burns the full iteration
    # budget on dynamically irrelevant mismatches (measured: 300 s/step at
    # 10 iterations while ||dv|| ~ 2e-5 m/s). With this floor, a step also
    # counts as converged when the per-marker RMS absolute mismatch (m/s) drops
    # below the floor: interface velocity errors far below the physical velocity
    # scale (mean inlet 0.2 m/s) cannot feed the added-mass loop.
    # 0.0 disables the absolute gate.
    fsi_coupling_absolute_tolerance_mps: float = 0.0
    # Optional maximum marker Euclidean velocity mismatch in m/s; None disables it.
    # Independent of the RMS floor and the internal marker-MAC no-slip tolerance.
    fsi_coupling_max_marker_tolerance_mps: float | None = None
    # Periodic flow-contour snapshot export (2026-07-09, observability parity
    # with the run-end export_final_flow_snapshot output): None (default)
    # preserves current behavior byte-for-byte -- nothing is written mid-run.
    # Set to an integer N to additionally write
    # output_dir/flow_snapshots/step_{step:06d}.npz every N physical steps,
    # reusing the SAME build_turek_hron_final_fields_snapshot builder as the
    # final export, so a velocity-contour animation can be rendered across the
    # whole run instead of only its last frame.
    flow_snapshot_interval_steps: int | None = None
    # Anisotropic IB classification envelope (gated, 2026-07-09; see the
    # _validate_marker_grid_consistency docstring for the full diagnosis).
    # False (default) preserves the scalar search_radius_m = 1.5*max(dy,dz)
    # envelope byte-for-byte. True switches run_turek_hron_fsi to a per-axis
    # box acceptance |d_i| < 1.5*h_i, so the boundary band scales with each
    # face's own normal cell size instead of the coarser of dy/dz. This is
    # what lets a y-only-refined grid (dy shrunk, dz unchanged) keep a thin
    # wall-normal band on the beam's long faces without the band reaching
    # through the beam interior -- the failure mode that produced 880x
    # spurious lift at rest on grid_nodes=(4, 96, 288) with the isotropic
    # envelope.
    ib_anisotropic_envelope: bool = False
    # Far-interior classification (2026-07-09, hardened 2026-09). The local
