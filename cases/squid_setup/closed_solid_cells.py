def open_edge_count(faces: np.ndarray) -> int:
    """Edges not shared by exactly two faces (zero for a closed two-manifold)."""
    edges = np.sort(
        np.concatenate((faces[:, [0, 1]], faces[:, [1, 2]], faces[:, [2, 0]])),
        axis=1,
    )
    _, counts = np.unique(edges, axis=0, return_counts=True)
    return int(np.count_nonzero(counts != 2))


# FastFsi: verbatim from cases/squid_soft_robot/closed_solid_cells.py lines 48-60
#          (source sha256 13065876cbeee983c9f40f02b0a55940fd71f4e8da3ba645dfd296f933b41a94)
def _orient2d(a: np.ndarray, b: np.ndarray, p: np.ndarray) -> np.ndarray:
    """(b - a) x (p - a) with an exact rational fallback when rounding could flip its sign."""
    left = (b[:, 0] - a[:, 0]) * (p[:, 1] - a[:, 1])
    right = (b[:, 1] - a[:, 1]) * (p[:, 0] - a[:, 0])
    det = left - right
    bound = 8.0 * np.finfo(np.float64).eps * (np.abs(left) + np.abs(right))
    for i in np.flatnonzero(np.abs(det) <= bound):
        ax, ay, bx, by, px, py = (
            Fraction(float(value))
            for value in (a[i, 0], a[i, 1], b[i, 0], b[i, 1], p[i, 0], p[i, 1])
        )
        det[i] = float((bx - ax) * (py - ay) - (by - ay) * (px - ax))
    return det


# FastFsi: verbatim from cases/squid_soft_robot/closed_solid_cells.py lines 63-85
#          (source sha256 13065876cbeee983c9f40f02b0a55940fd71f4e8da3ba645dfd296f933b41a94)
def _oriented_edge(
    start: np.ndarray,
    end: np.ndarray,
    point: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    """Edge function of start->end at point, and its sign with ties broken.

    The value is computed from the canonical endpoint order, so the two faces
    sharing an edge evaluate bit-identical magnitudes of opposite sign. An exact
    zero takes the sign of the derivative along the perturbation (1, eta),
    eta -> 0+, which every edge shares.
    """
    swap = (start[:, 0] > end[:, 0]) | (
        (start[:, 0] == end[:, 0]) & (start[:, 1] > end[:, 1])
    )
    low = np.where(swap[:, None], end, start)
    high = np.where(swap[:, None], start, end)
    dv = high[:, 1] - low[:, 1]
    canonical = _orient2d(low, high, point)
    tie = np.where(dv != 0.0, -dv, 1.0)
    orientation = np.where(swap, -1.0, 1.0)
    signed = orientation * np.where(canonical != 0.0, canonical, tie)
    return orientation * canonical, signed


# FastFsi: verbatim from cases/squid_soft_robot/closed_solid_cells.py lines 88-138
#          (source sha256 13065876cbeee983c9f40f02b0a55940fd71f4e8da3ba645dfd296f933b41a94)
def _line_crossings(
    tri_uv: np.ndarray,
    tri_w: np.ndarray,
    line_u: np.ndarray,
    line_v: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    """Crossings of the lines (line_u[a], line_v[b], w) with the triangles.

    Returns the flat line index ``a * len(line_v) + b`` and the crossing
    coordinate ``w`` of every crossing.
    """
    area2 = _orient2d(tri_uv[:, 0], tri_uv[:, 1], tri_uv[:, 2])
    a_start = np.searchsorted(line_u, tri_uv[:, :, 0].min(axis=1), side="left")
    a_stop = np.searchsorted(line_u, tri_uv[:, :, 0].max(axis=1), side="right")
    b_start = np.searchsorted(line_v, tri_uv[:, :, 1].min(axis=1), side="left")
    b_stop = np.searchsorted(line_v, tri_uv[:, :, 1].max(axis=1), side="right")
    a_count = np.maximum(a_stop - a_start, 0)
    b_count = np.maximum(b_stop - b_start, 0)
    # A face parallel to the lines has no crossing for any perturbed line.
    pair_count = np.where(area2 != 0.0, a_count * b_count, 0).astype(np.int64)
    faces = np.flatnonzero(pair_count)
    line_ids: list[np.ndarray] = []
    coordinates: list[np.ndarray] = []
    ends = np.cumsum(pair_count[faces])
    starts = ends - pair_count[faces]
    total = int(ends[-1]) if ends.size else 0
    for begin in range(0, total, _PAIR_CHUNK):
        pair = np.arange(begin, min(begin + _PAIR_CHUNK, total), dtype=np.int64)
        position = np.searchsorted(ends, pair, side="right")
        face = faces[position]
        offset = pair - starts[position]
        a = a_start[face] + offset // b_count[face]
        b = b_start[face] + offset % b_count[face]
        point = np.stack((line_u[a], line_v[b]), axis=1)
        e01, s01 = _oriented_edge(tri_uv[face, 0], tri_uv[face, 1], point)
        e12, s12 = _oriented_edge(tri_uv[face, 1], tri_uv[face, 2], point)
        e20, s20 = _oriented_edge(tri_uv[face, 2], tri_uv[face, 0], point)
        sigma = np.sign(area2[face])
        hit = (sigma * s01 > 0.0) & (sigma * s12 > 0.0) & (sigma * s20 > 0.0)
        face = face[hit]
        w = (
            e12[hit] * tri_w[face, 0]
            + e20[hit] * tri_w[face, 1]
            + e01[hit] * tri_w[face, 2]
        ) / area2[face]
        w = np.clip(w, tri_w[face].min(axis=1), tri_w[face].max(axis=1))
        line_ids.append(a[hit] * line_v.size + b[hit])
        coordinates.append(w)
    if not line_ids:
        return np.zeros(0, dtype=np.int64), np.zeros(0, dtype=np.float64)
    return np.concatenate(line_ids), np.concatenate(coordinates)


# FastFsi: verbatim from cases/squid_soft_robot/closed_solid_cells.py lines 141-183
#          (source sha256 13065876cbeee983c9f40f02b0a55940fd71f4e8da3ba645dfd296f933b41a94)
def _axis_classification(
    triangles: np.ndarray,
    centres: tuple[np.ndarray, np.ndarray, np.ndarray],
    axis: int,
) -> tuple[np.ndarray, int, tuple[np.ndarray, ...]]:
    """Centre parity along ``axis`` (in (x, y, z) order), the odd-line count and
    the inside intervals that hold no centre: (line, first centre above, enter, leave)."""
    u_axis, v_axis = (value for value in range(3) if value != axis)
    line_u, line_v, line_w = centres[u_axis], centres[v_axis], centres[axis]
    line, w = _line_crossings(
        triangles[:, :, [u_axis, v_axis]],
        triangles[:, :, axis],
        line_u,
        line_v,
    )
    line_count = line_u.size * line_v.size
    order = np.lexsort((w, line))
    line = line[order]
    w = w[order]
    per_line = np.bincount(line, minlength=line_count)
    odd_lines = int(np.count_nonzero(per_line % 2))
    shape = (line_u.size, line_v.size, line_w.size)
    inside = np.zeros(shape, dtype=bool)
    empty_intervals: tuple[np.ndarray, ...] = (np.zeros(0, dtype=np.int64),) * 2 + (
        np.zeros(0),
    ) * 2
    if odd_lines == 0 and w.size:
        # Consecutive crossings on a line bound the inside intervals.
        enter = w[0::2]
        leave = w[1::2]
        interval_line = line[0::2]
        first = np.searchsorted(line_w, enter, side="right")
        last = np.searchsorted(line_w, leave, side="right")
        coverage = np.zeros((line_count, line_w.size + 1), dtype=np.int32)
        np.add.at(coverage, (interval_line, first), 1)
        np.add.at(coverage, (interval_line, last), -1)
        np.cumsum(coverage[:, :-1], axis=1, dtype=np.int32, out=coverage[:, :-1])
        inside = (coverage[:, :-1] > 0).reshape(shape)
        # Zero-length (tangent) intervals hold no material.
        empty = (first == last) & (leave > enter)
        empty_intervals = (interval_line[empty], first[empty], enter[empty], leave[empty])
    order_to_xyz = tuple(int(value) for value in np.argsort((u_axis, v_axis, axis)))
    return inside.transpose(order_to_xyz), odd_lines, empty_intervals


# FastFsi: verbatim from cases/squid_soft_robot/closed_solid_cells.py lines 186-214
#          (source sha256 13065876cbeee983c9f40f02b0a55940fd71f4e8da3ba645dfd296f933b41a94)
def _thin_wall_cells(
    by_centre: np.ndarray,
    cell_faces: tuple[np.ndarray, np.ndarray, np.ndarray],
    axis: int,
    empty_intervals: tuple[np.ndarray, ...],
) -> np.ndarray:
    """Cells closing walls that lie between two fluid centres on a line.

    The cell holding the wall interval's midpoint becomes solid unless one of
    the two centres bracketing the interval is already solid (nothing to close).
    """
    u_axis, v_axis = (value for value in range(3) if value != axis)
    shape = by_centre.shape
    count_w = shape[axis]
    line_count = shape[u_axis] * shape[v_axis]
    occupied = by_centre.transpose(u_axis, v_axis, axis).reshape(line_count, count_w)
    line, first, enter, leave = empty_intervals
    interior = (first > 0) & (first < count_w)
    redundant = np.zeros(line.size, dtype=bool)
    redundant[interior] = (
        occupied[line[interior], first[interior] - 1] | occupied[line[interior], first[interior]]
    )
    line, enter, leave = line[~redundant], enter[~redundant], leave[~redundant]
    cell = np.searchsorted(cell_faces[axis], 0.5 * (enter + leave), side="right") - 1
    in_grid = (cell >= 0) & (cell < count_w)
    thin = np.zeros((line_count, count_w), dtype=bool)
    thin[line[in_grid], cell[in_grid]] = True
    order_to_xyz = tuple(int(value) for value in np.argsort((u_axis, v_axis, axis)))
    return thin.reshape(shape[u_axis], shape[v_axis], count_w).transpose(order_to_xyz)


# FastFsi: verbatim from cases/squid_soft_robot/closed_solid_cells.py lines 217-293
#          (source sha256 13065876cbeee983c9f40f02b0a55940fd71f4e8da3ba645dfd296f933b41a94)
def classify_closed_solid_cells(
    triangles_m: np.ndarray,
    grid: CartesianGrid,
    *,
    close_thin_walls: bool = True,
) -> tuple[np.ndarray, dict[str, object]]:
    """Solid cells of one closed triangulated solid (triangles in metres).

    ``close_thin_walls=False`` returns the cell-centre classification alone
    (material points), without the cells that seal walls between centres.
    """
    points, faces = weld_exact_vertices(triangles_m)
    open_edges = open_edge_count(faces)
    if open_edges:
        raise ValueError(
            f"rigid solid surface is not closed: {open_edges} edges are not shared "
            "by exactly two faces"
        )
    triangles = points[faces]
    centres = (
        np.asarray(grid.cell_centers_x_m, dtype=np.float64),
        np.asarray(grid.cell_centers_y_m, dtype=np.float64),
        np.asarray(grid.cell_centers_z_m, dtype=np.float64),
    )
    cell_faces = (
        np.asarray(grid.cell_faces_x_m, dtype=np.float64),
        np.asarray(grid.cell_faces_y_m, dtype=np.float64),
        np.asarray(grid.cell_faces_z_m, dtype=np.float64),
    )
    shape = tuple(int(value.size) for value in centres)
    votes = np.zeros(shape, dtype=np.int8)
    odd_lines: list[int] = []
    empty_intervals: list[tuple[np.ndarray, ...]] = []
    for axis in range(3):
        inside, odd, empty = _axis_classification(triangles, centres, axis)
        votes += inside
        odd_lines.append(odd)
        empty_intervals.append(empty)
    if any(odd_lines):
        raise ValueError(
            "closed-solid line parity failed: lines with an odd crossing count "
            f"per axis {tuple(odd_lines)}"
        )
    by_centre = votes >= 2
    thin = np.zeros(shape, dtype=bool)
    if close_thin_walls:
        for axis in range(3):
            thin |= _thin_wall_cells(by_centre, cell_faces, axis, empty_intervals[axis])
    thin_only = thin & ~by_centre
    solid = by_centre | thin_only
    volume = float(
        np.einsum(
            "ij,ij->i",
            triangles[:, 0],
            np.cross(triangles[:, 1], triangles[:, 2]),
        ).sum()
        / 6.0
    )
    widths = np.einsum(
        "i,j,k->ijk",
        np.diff(cell_faces[0]),
        np.diff(cell_faces[1]),
        np.diff(cell_faces[2]),
    )
    return solid, {
        "method": "closed_solid_cell_centre_parity_three_axis_vote",
        "face_count": int(faces.shape[0]),
        "welded_vertex_count": int(points.shape[0]),
        "enclosed_volume_m3": abs(volume),
        "solid_cell_count": int(np.count_nonzero(solid)),
        "solid_cell_volume_m3": float(widths[solid].sum()),
        "centre_inside_cell_count": int(np.count_nonzero(by_centre)),
        "thin_wall_cell_count": int(np.count_nonzero(thin_only)),
        "axis_vote_disagreement_cell_count": int(
            np.count_nonzero((votes != 0) & (votes != 3))
        ),
    }


# FastFsi: verbatim from cases/squid_soft_robot/closed_solid_cells.py lines 296-328
#          (source sha256 13065876cbeee983c9f40f02b0a55940fd71f4e8da3ba645dfd296f933b41a94)
def _ray_hit_distances(
    origin: np.ndarray,
    directions: np.ndarray,
    triangles: np.ndarray,
) -> list[np.ndarray]:
    """Distinct sorted distances to the faces along each in-plane direction.

    The barycentric bounds are widened slightly so a ray through a shared edge
    cannot slip between its two faces; the duplicate hit this allows at an
    edge is merged.
    """
    v0 = triangles[:, 0]
    edge1 = triangles[:, 1] - v0
    edge2 = triangles[:, 2] - v0
    to_origin = origin - v0
    scale = max(1.0, float(np.max(np.abs(origin))))
    tolerance = 64.0 * np.finfo(np.float64).eps * scale
    hits: list[np.ndarray] = []
    for direction in directions:
        p = np.cross(direction, edge2)
        det = np.einsum("ij,ij->i", edge1, p)
        valid = np.abs(det) > 1.0e-30
        inv = np.divide(1.0, det, out=np.zeros_like(det), where=valid)
        u = np.einsum("ij,ij->i", to_origin, p) * inv
        q = np.cross(to_origin, edge1)
        v = (q @ direction) * inv
        t = np.einsum("ij,ij->i", edge2, q) * inv
        hit = valid & (u >= -1.0e-9) & (v >= -1.0e-9) & (u + v <= 1.0 + 1.0e-9) & (t > 0.0)
        distances = np.sort(t[hit])
        if distances.size:
            distances = distances[np.r_[True, np.diff(distances) > tolerance]]
        hits.append(distances)
    return hits


# FastFsi: verbatim from cases/squid_soft_robot/closed_solid_cells.py lines 331-369
#          (source sha256 13065876cbeee983c9f40f02b0a55940fd71f4e8da3ba645dfd296f933b41a94)
def nozzle_lumen_section(
    triangles_m: np.ndarray,
    *,
    z_m: float,
    axis_xy_m: tuple[float, float],
    ray_count: int = 720,
) -> dict[str, float]:
    """Area and centroid of the star-shaped lumen around the axis at height z.

    Every ray from the axis must cross exactly one wall interval (lumen ->
    material -> exterior); otherwise the axis is not inside a simple lumen.
    """
    theta = (np.arange(ray_count) + 0.5) * (2.0 * math.pi / ray_count)
    directions = np.stack(
        (np.cos(theta), np.sin(theta), np.zeros_like(theta)), axis=1
    )
    origin = np.asarray((axis_xy_m[0], axis_xy_m[1], z_m), dtype=np.float64)
    spans = (triangles_m[:, :, 2].min(axis=1) <= z_m) & (
        triangles_m[:, :, 2].max(axis=1) >= z_m
    )
    hits = _ray_hit_distances(origin, directions, triangles_m[spans])
    if any(distances.size != 2 for distances in hits):
        raise ValueError(
            f"nozzle section at z = {z_m:.6f} m is not one lumen-to-exterior wall interval"
        )
    radius = np.asarray([float(distances[0]) for distances in hits])
    step = 2.0 * math.pi / ray_count
    area = 0.5 * float(np.sum(radius**2)) * step
    centroid_x = float(np.sum(radius**3 * np.cos(theta)) * step / (3.0 * area))
    centroid_y = float(np.sum(radius**3 * np.sin(theta)) * step / (3.0 * area))
    return {
        "z_m": float(z_m),
        "area_m2": area,
        "equivalent_radius_m": math.sqrt(area / math.pi),
        "radius_min_m": float(radius.min()),
        "radius_max_m": float(radius.max()),
        "centroid_x_m": float(axis_xy_m[0]) + centroid_x,
        "centroid_y_m": float(axis_xy_m[1]) + centroid_y,
    }


# FastFsi: verbatim from cases/squid_soft_robot/closed_solid_cells.py lines 372-403
#          (source sha256 13065876cbeee983c9f40f02b0a55940fd71f4e8da3ba645dfd296f933b41a94)
def nozzle_exit_geometry(
    triangles_m: np.ndarray,
    *,
    profile_heights_m: tuple[float, ...] = (2.0e-5, 1.0e-4, 2.5e-4, 5.0e-4, 1.0e-3, 2.0e-3, 3.0e-3),
) -> dict[str, object]:
    """Exit plane, axis and lumen profile of a closed nozzle body opening at its lowest point."""
    corners = triangles_m.reshape(-1, 3)
    exit_z = float(corners[:, 2].min())
    lip = corners[corners[:, 2] == exit_z]
    axis = (float(lip[:, 0].mean()), float(lip[:, 1].mean()))
    # Recentre on the lumen centroid just above the lip.
    for _ in range(3):
        section = nozzle_lumen_section(
            triangles_m, z_m=exit_z + profile_heights_m[0], axis_xy_m=axis
        )
        axis = (section["centroid_x_m"], section["centroid_y_m"])
    profile = [
        nozzle_lumen_section(triangles_m, z_m=exit_z + height, axis_xy_m=axis)
        for height in profile_heights_m
    ]
    throat = min(profile, key=lambda item: item["area_m2"])
    return {
        "exit_z_m": exit_z,
        "axis_xy_m": axis,
        "exit_section_z_m": profile[0]["z_m"],
        "exit_area_m2": profile[0]["area_m2"],
        "exit_equivalent_radius_m": profile[0]["equivalent_radius_m"],
        "throat_estimator": "minimum_of_sampled_sections",
        "throat_area_m2": throat["area_m2"],
        "throat_z_m": throat["z_m"],
        "lumen_profile": tuple(profile),
    }


# FastFsi: verbatim from cases/squid_soft_robot/closed_solid_cells.py lines 406-515
#          (source sha256 13065876cbeee983c9f40f02b0a55940fd71f4e8da3ba645dfd296f933b41a94)
def nozzle_lumen_staircase_report(
    active_water: np.ndarray,
    grid: CartesianGrid,
    triangles_m: np.ndarray,
    exit_geometry: dict[str, object],
    *,
    tolerance: float = 0.05,
    exit_band_m: float = 3.0e-3,
    upstream_row_tolerance: float = 0.10,
    bore_top_z_m: float | None = None,
) -> dict[str, object]:
    """Voxelised nozzle lumen against the exact CAD sections, rows and faces.

    The lumen of a cell row is the 4-connected active region holding the axis
    cell; the open face below row k is that region's part whose lower cell is
    active (the flow area between rows k - 1 and k). Every row and face from the
    exit up to the bore top must be open. Within ``exit_band_m`` of the exit,
    row and face areas must match the exact sections within ``tolerance``;
    upstream, rows within ``upstream_row_tolerance`` and every face at least
    (1 - tolerance) of the sampled throat area.
    """
    from scipy.ndimage import label

    axis_x, axis_y = exit_geometry["axis_xy_m"]
    exit_z = float(exit_geometry["exit_z_m"])
    top_z = float(triangles_m[:, :, 2].max()) if bore_top_z_m is None else float(bore_top_z_m)
    centres_z = np.asarray(grid.cell_centers_z_m, dtype=np.float64)
    faces_z = np.asarray(grid.cell_faces_z_m, dtype=np.float64)
    widths_x = np.diff(np.asarray(grid.cell_faces_x_m, dtype=np.float64))
    widths_y = np.diff(np.asarray(grid.cell_faces_y_m, dtype=np.float64))
    i_axis = int(np.searchsorted(grid.cell_faces_x_m, axis_x, side="right") - 1)
    j_axis = int(np.searchsorted(grid.cell_faces_y_m, axis_y, side="right") - 1)
    if not (0 <= i_axis < active_water.shape[0] and 0 <= j_axis < active_water.shape[1]):
        raise ValueError("nozzle axis lies outside the fluid grid")
    rows = np.flatnonzero((centres_z > exit_z) & (centres_z < top_z))
    if rows.size == 0 or rows[0] == 0:
        raise ValueError("the nozzle bore lies outside the fluid grid")
    cell_area = np.outer(widths_x, widths_y)
    throat = float(exit_geometry["throat_area_m2"])

    def section(z: float) -> float:
        return float(
            nozzle_lumen_section(triangles_m, z_m=z, axis_xy_m=(axis_x, axis_y))["area_m2"]
        )

    records = []
    for k in rows:
        in_band = bool(centres_z[k] <= exit_z + exit_band_m)
        open_area = face_area = 0.0
        if active_water[i_axis, j_axis, k]:
            labels, _ = label(active_water[:, :, k])
            lumen = labels == labels[i_axis, j_axis]
            open_area = float(cell_area[lumen].sum())
            face_area = float(cell_area[lumen & active_water[:, :, k - 1]].sum())
        exact_row = section(float(centres_z[k]))
        face_z = max(float(faces_z[k]), exit_z + 2.0e-5)
        exact_face = section(face_z) if face_z <= exit_z + exit_band_m else None
        records.append(
            {
                "k": int(k),
                "z_m": float(centres_z[k]),
                "exit_band": in_band,
                "open_area_m2": open_area,
                "exact_area_m2": exact_row,
                "relative_error": open_area / exact_row - 1.0,
                "face_z_m": face_z,
                "open_face_area_m2": face_area,
                "exact_face_area_m2": exact_face,
                "face_relative_error": (
                    None if exact_face is None else face_area / exact_face - 1.0
                ),
            }
        )
    band = [item for item in records if item["exit_band"]]
    upstream = [item for item in records if not item["exit_band"]]
    band_faces = [item for item in records if item["face_relative_error"] is not None]
    report = {
        "axis_cell_ij": (i_axis, j_axis),
        "row_count": len(records),
        "bore_top_z_m": top_z,
        "tolerance": float(tolerance),
        "upstream_row_tolerance": float(upstream_row_tolerance),
        "closed_row_count": int(sum(1 for item in records if item["open_area_m2"] == 0.0)),
        "closed_face_count": int(
            sum(1 for item in records if item["open_face_area_m2"] == 0.0)
        ),
        "max_abs_relative_error": max(abs(item["relative_error"]) for item in band) if band else 0.0,
        "max_abs_face_relative_error": (
            max(abs(item["face_relative_error"]) for item in band_faces) if band_faces else 0.0
        ),
        "max_abs_upstream_row_error": (
            max(abs(item["relative_error"]) for item in upstream) if upstream else 0.0
        ),
        "min_face_to_throat_ratio": min(item["open_face_area_m2"] for item in records) / throat,
        "cells_across_exit_diameter": float(
            2.0
            * float(exit_geometry["exit_equivalent_radius_m"])
            / max(float(widths_x[i_axis]), float(widths_y[j_axis]))
        ),
        "rows": tuple(records),
    }
    report["passed"] = bool(
        report["closed_row_count"] == 0
        and report["closed_face_count"] == 0
        and report["max_abs_relative_error"] <= tolerance
        and report["max_abs_face_relative_error"] <= tolerance
        and report["max_abs_upstream_row_error"] <= upstream_row_tolerance
        and report["min_face_to_throat_ratio"] >= 1.0 - tolerance
    )
    return report


