def triangle_surface_samples(
    triangles: np.ndarray,
    spacing_m: float,
) -> tuple[np.ndarray, np.ndarray]:
    """Points covering every triangle at about ``spacing_m`` (vectorised by sample count).

    Returns the points and the index of the triangle each point lies on.
    """
    tri = np.asarray(triangles, dtype=np.float64)
    longest = np.max(
        np.stack(
            (
                np.linalg.norm(tri[:, 1] - tri[:, 0], axis=1),
                np.linalg.norm(tri[:, 2] - tri[:, 0], axis=1),
                np.linalg.norm(tri[:, 2] - tri[:, 1], axis=1),
            )
        ),
        axis=0,
    )
    counts = np.maximum(2, np.ceil(longest / float(spacing_m)).astype(np.int64) + 1)
    points: list[np.ndarray] = []
    owners: list[np.ndarray] = []
    for n in np.unique(counts):
        group = np.flatnonzero(counts == n)
        u, v = np.meshgrid(np.linspace(0.0, 1.0, n), np.linspace(0.0, 1.0, n))
        keep = (u + v) <= 1.0
        u, v = u[keep], v[keep]
        a = tri[group, 0][:, None, :]
        points.append(
            (a + u[None, :, None] * (tri[group, 1] - tri[group, 0])[:, None, :]
             + v[None, :, None] * (tri[group, 2] - tri[group, 0])[:, None, :]).reshape(-1, 3)
        )
        owners.append(np.repeat(group, u.size))
    return np.concatenate(points), np.concatenate(owners)
