def _mapping_config_float(
    mapping: Mapping[str, object],
    keys: Sequence[str],
    default: float,
    *,
    field: str,
) -> float:
    for key in keys:
        if key in mapping:
            value = float(mapping[key])
            if not math.isfinite(value):
                raise ValueError(f"{field} must be finite")
            return value
    return float(default)


