def source_config_part_material(
    config: Mapping[str, object],
    region_id: int,
) -> dict[str, object] | None:
    """Material (E, nu, rho) of the CAD part whose faces contain region_id's faces."""
    faces = set(_face_ids_for_region(dict(config), int(region_id)))
    selections = config.get("named_selections", [])
    if not faces or not isinstance(selections, list):
        return None
    for selection in selections:
        if not isinstance(selection, Mapping) or int(selection.get("id", -1)) == int(region_id):
            continue
        props = selection.get("mat_props") or {}
        if not isinstance(props, Mapping) or not {"E_Pa", "nu"} <= set(props):
            continue
        if faces <= set(selection.get("face_ids", []) or []):
            density = props.get("rho_kgm3", props.get("rho"))
            if density is None:
                raise ValueError(f"part {selection.get('id')} material has no density")
            return {
                "part_region_id": int(selection["id"]),
                "material_name": str(selection.get("material", "")),
                "youngs_modulus_pa": float(props["E_Pa"]),
                "poissons_ratio": float(props["nu"]),
                "density_kgm3": float(density),
            }
    return None


