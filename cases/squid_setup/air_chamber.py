import numpy as np
import taichi as ti


# FastFsi: verbatim from cases/squid_soft_robot/air_chamber.py lines 17-141
#          (source sha256 85c6ebadcdd398bf5608af588889513dce65078605f584d47c416d8d27a282c8)
@ti.data_oriented
class AirChamberColumns:
    """Marks the air above the membrane in a dynamic solid-volume candidate.

    In every fluid column inside the chamber cross-section, the cells whose
    centre lies above the membrane's mid-surface there (mean height of the
    membrane particles in the column) and below the lid are air. The
    mid-surface is at least half a membrane thickness above the water face,
    so water is never marked, and the overlap with the rasterised membrane
    leaves no fluid gap. A footprint column without membrane particles is a
    hole and raises. The air cells are kept separately for an audit after
    the interface classification (they must stay solid).
    """

    def __init__(
        self,
        footprint: np.ndarray,
        *,
        cell_faces_x_m: np.ndarray,
        cell_faces_y_m: np.ndarray,
        cell_centers_z_m: np.ndarray,
        lid_z_m: float,
        membrane_region_id: int,
    ):
        footprint = np.asarray(footprint, dtype=bool)
        if footprint.ndim != 2 or not footprint.any():
            raise ValueError("the air chamber footprint must be a non-empty (nx, ny) mask")
        nx, ny = footprint.shape
        nz = len(cell_centers_z_m)
        if len(cell_faces_x_m) != nx + 1 or len(cell_faces_y_m) != ny + 1:
            raise ValueError("cell faces do not match the footprint")
        self.shape = (nx, ny, nz)
        self.column_count = int(footprint.sum())
        self.lid_z_m = float(lid_z_m)
        self.membrane_region_id = int(membrane_region_id)
        self.footprint = ti.field(ti.i32, shape=(nx, ny))
        self.footprint.from_numpy(footprint.astype(np.int32))
        self.face_x = ti.field(ti.f64, shape=nx + 1)
        self.face_y = ti.field(ti.f64, shape=ny + 1)
        self.centre_z = ti.field(ti.f64, shape=nz)
        self.face_x.from_numpy(np.asarray(cell_faces_x_m, dtype=np.float64))
        self.face_y.from_numpy(np.asarray(cell_faces_y_m, dtype=np.float64))
        self.centre_z.from_numpy(np.asarray(cell_centers_z_m, dtype=np.float64))
        self.column_sum = ti.field(ti.f64, shape=(nx, ny))
        self.column_count_field = ti.field(ti.i32, shape=(nx, ny))
        self.air = ti.field(ti.i8, shape=self.shape)
        # air cells, footprint columns without membrane particles, active air cells (audit)
        self.counters = ti.field(ti.i32, shape=3)
        self.last_air_cell_count = 0

    @ti.func
    def _locate(self, faces: ti.template(), n: ti.i32, value: ti.f64) -> ti.i32:
        index = -1
        if value >= faces[0] and value < faces[n]:
            low, high = 0, n
            while high - low > 1:
                middle = (low + high) // 2
                if faces[middle] <= value:
                    low = middle
                else:
                    high = middle
            index = low
        return index

    @ti.kernel
    def _accumulate(self, x: ti.template(), region: ti.template(), count: ti.i32, membrane: ti.i32):
        for i, j in self.column_sum:
            self.column_sum[i, j] = 0.0
            self.column_count_field[i, j] = 0
        for p in range(count):
            if region[p] == membrane:
                position = x[p].cast(ti.f64)
                i = self._locate(self.face_x, self.shape[0], position.x)
                j = self._locate(self.face_y, self.shape[1], position.y)
                if i >= 0 and j >= 0:
                    ti.atomic_add(self.column_sum[i, j], position.z)
                    ti.atomic_add(self.column_count_field[i, j], 1)

    def accumulate(self, particle_position_m, particle_region_id, particle_count: int) -> None:
        """Membrane mid-surface per column from the current particles."""
        self._accumulate(particle_position_m, particle_region_id, int(particle_count), self.membrane_region_id)

    @ti.kernel
    def _fill(self, candidate: ti.template(), base: ti.template(), lid_z: ti.f64):
        self.counters[0] = 0
        self.counters[1] = 0
        for i, j in self.footprint:
            if self.footprint[i, j] != 0:
                count = self.column_count_field[i, j]
                middle = ti.cast(1.0e30, ti.f64)
                if count == 0:
                    ti.atomic_add(self.counters[1], 1)
                else:
                    middle = self.column_sum[i, j] / ti.cast(count, ti.f64)
                for k in range(self.shape[2]):
                    self.air[i, j, k] = 0
                    z = self.centre_z[k]
                    if z > middle and z < lid_z and base[i, j, k] == 0:
                        candidate[i, j, k] = 1
                        self.air[i, j, k] = 1
                        ti.atomic_add(self.counters[0], 1)

    def __call__(self, candidate, base) -> None:
        if tuple(candidate.shape) != self.shape or tuple(base.shape) != self.shape:
            raise ValueError("air chamber columns do not match the fluid grid")
        self._fill(candidate, base, self.lid_z_m)
        counters = self.counters.to_numpy()
        self.last_air_cell_count = int(counters[0])
        if int(counters[1]) > 0:
            raise RuntimeError(
                f"air chamber: {int(counters[1])} of {self.column_count} chamber columns hold no "
                "membrane particle (the membrane left the chamber cross-section or tore)"
            )

    @ti.kernel
    def _count_active_air(self, obstacle: ti.template()):
        self.counters[2] = 0
        for i, j, k in self.air:
            if self.air[i, j, k] != 0 and obstacle[i, j, k] == 0:
                ti.atomic_add(self.counters[2], 1)

    def audit(self, obstacle) -> int:
        """Air cells that the interface classification reopened as water (must be zero)."""
        self._count_active_air(obstacle)
        return int(self.counters.to_numpy()[2])
