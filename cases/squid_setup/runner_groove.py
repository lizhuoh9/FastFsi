GROOVE_Z_MAX_M = 1.0180


# FastFsi: verbatim from UDF/m2_inputs/squid_runner_groove.py lines 29-29
#          (source sha256 b9ddcb0ee280e9d4deb1d33a5eaa4bb9ef087188d2572c7dad5537d920de99d0)
CONTAINMENT_R_MAX_M = 0.036


# FastFsi: verbatim from UDF/m2_inputs/squid_runner_groove.py lines 34-36
#          (source sha256 b9ddcb0ee280e9d4deb1d33a5eaa4bb9ef087188d2572c7dad5537d920de99d0)
def _centers(lo, widths):
    w = np.asarray(widths, dtype=np.float64)
    return lo + np.cumsum(w) - 0.5 * w


# FastFsi: verbatim from UDF/m2_inputs/squid_runner_groove.py lines 39-79
#          (source sha256 b9ddcb0ee280e9d4deb1d33a5eaa4bb9ef087188d2572c7dad5537d920de99d0)
def carve_groove(obstacle, grid):
    cx = _centers(grid.bounds_min_m[0], grid.cell_widths_x_m)
    cy = _centers(grid.bounds_min_m[1], grid.cell_widths_y_m)
    cz = _centers(grid.bounds_min_m[2], grid.cell_widths_z_m)
    mask = np.asarray(obstacle)
    if mask.shape != (cx.size, cy.size, cz.size):
        raise RuntimeError(f"groove: obstacle shape {mask.shape} != grid {(cx.size, cy.size, cz.size)}")
    radius = np.hypot(cx[:, None] - AXIS_XY_M[0], cy[None, :] - AXIS_XY_M[1])
    ring = (radius >= GROOVE_R_INNER_M) & (radius < GROOVE_R_OUTER_M)
    layers = np.nonzero((cz >= GROOVE_Z_MIN_M) & (cz <= GROOVE_Z_MAX_M))[0]
    carved = mask.copy()
    per_layer = {}
    for k in layers:
        hit = ring & (carved[:, :, k] != 0)
        carved[:, :, k][hit] = 0
        per_layer[float(cz[k])] = int(hit.sum())
    # containment: 2-D flood (4-connectivity) from the chamber interior must stay inside the groove
    from scipy import ndimage
    interior = radius < 0.025
    for k in layers:
        fluid = carved[:, :, k] == 0
        labels, _ = ndimage.label(fluid)
        ids = np.unique(labels[interior & fluid])
        ids = ids[ids != 0]
        reach = np.isin(labels, ids)
        if reach.any() and float(radius[reach].max()) >= CONTAINMENT_R_MAX_M:
            raise RuntimeError(
                f"groove breached the chamber wall at z={cz[k]:.5f} m: chamber water reaches r="
                f"{radius[reach].max() * 1e3:.2f} mm"
            )
    total = int(sum(per_layer.values()))
    if total == 0:
        raise RuntimeError("groove carved no cells: geometry/axis mismatch")
    return carved.astype(mask.dtype, copy=False), {
        "groove_carved_cells": total,
        "groove_layers": len(layers),
        "groove_r_m": [GROOVE_R_INNER_M, GROOVE_R_OUTER_M],
        "groove_z_m": [GROOVE_Z_MIN_M, GROOVE_Z_MAX_M],
        "groove_axis_xy_m": list(AXIS_XY_M),
        "groove_containment_r_max_m": CONTAINMENT_R_MAX_M,
    }
