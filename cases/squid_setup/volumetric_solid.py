def _rigid_region_ids(config: Mapping[str, object]) -> tuple[int, ...]:
    analysis = config.get("analysis_settings", {})
    return _selection_ids_as_int_tuple(
        analysis.get("solid_obstacle_surface_only_region_ids", ()) if isinstance(analysis, Mapping) else ()
    )


# FastFsi: verbatim from cases/squid_soft_robot/volumetric_solid.py lines 210-231
#          (source sha256 2bca31d40e9be8f3f001ac2df44feb09a1d9f4589b430d0353207843f60bcc43)
def source_config_squid_air_chamber(
    config: Mapping[str, object],
    *,
    primary_surface_region_id: int,
    secondary_surface_region_id: int,
    air_face_region_id: int,
) -> SquidAirChamber:
    """The air chamber of the source-config CAD (membrane faces, valve part, rigid bodies)."""
    valve = source_config_part_material(config, int(secondary_surface_region_id))
    if valve is None:
        raise ValueError(f"no CAD part contains FSI surface region {secondary_surface_region_id}")
    rigid_ids = _rigid_region_ids(config)
    triangles = _region_triangles_m(
        config,
        (int(air_face_region_id), int(primary_surface_region_id), int(valve["part_region_id"]), *rigid_ids),
    )
    return squid_air_chamber_geometry(
        air_face_triangles=triangles[int(air_face_region_id)],
        water_face_triangles=triangles[int(primary_surface_region_id)],
        valve_triangles=triangles[int(valve["part_region_id"])],
        rigid_triangles=[triangles[region] for region in rigid_ids],
    )


# FastFsi: verbatim from cases/squid_soft_robot/volumetric_solid.py lines 462-471
#          (source sha256 2bca31d40e9be8f3f001ac2df44feb09a1d9f4589b430d0353207843f60bcc43)
def air_chamber_footprint(
    air_chamber: SquidAirChamber,
    *,
    cell_centers_x_m: np.ndarray,
    cell_centers_y_m: np.ndarray,
) -> np.ndarray:
    """Fluid columns whose centre lies inside the air chamber's cross-section."""
    x = np.asarray(cell_centers_x_m)[:, None] - air_chamber.axis_xy_m[0]
    y = np.asarray(cell_centers_y_m)[None, :] - air_chamber.axis_xy_m[1]
    return np.hypot(x, y) < air_chamber.inner_radius_m
