def _require_outward_closed_body(triangles: np.ndarray, name: str) -> None:
    """Every edge joins two faces with opposite directions and the volume is positive.

    Marker normals and the one-sided pressure side come from the triangle
    winding, so a body wound inward (or inconsistently) is rejected.
    """
    points, faces = weld_exact_vertices(triangles)
    directed = np.concatenate((faces[:, [0, 1]], faces[:, [1, 2]], faces[:, [2, 0]]))
    _, counts = np.unique(directed, axis=0, return_counts=True)
    reverse = {tuple(edge) for edge in directed[:, ::-1].tolist()}
    unmatched = sum(tuple(edge) not in reverse for edge in directed.tolist())
    if np.any(counts != 1) or unmatched:
        raise ValueError(f"{name}: surface is not a consistently wound closed two-manifold")
    tri = points[faces]
    volume = np.einsum("ij,ij->i", tri[:, 0], np.cross(tri[:, 1], tri[:, 2])).sum() / 6.0
    if not volume > 0.0:
        raise ValueError(f"{name}: triangles are wound inward (signed volume {volume:.3e} m^3)")


# FastFsi: verbatim from cases/squid_soft_robot/volumetric_solid.py lines 146-200
#          (source sha256 2bca31d40e9be8f3f001ac2df44feb09a1d9f4589b430d0353207843f60bcc43)
def squid_air_chamber_geometry(
    *,
    air_face_triangles: np.ndarray,
    water_face_triangles: np.ndarray,
    valve_triangles: np.ndarray,
    rigid_triangles: list[np.ndarray],
) -> SquidAirChamber:
    """Axis, radius and lid of the air chamber above a flat membrane disc."""
    air = air_face_triangles.reshape(-1, 3)
    water = water_face_triangles.reshape(-1, 3)
    air_z, water_z = float(air[:, 2].max()), float(water[:, 2].max())
    if np.ptp(air[:, 2]) > 1.0e-6 or np.ptp(water[:, 2]) > 1.0e-6 or not air_z > water_z:
        raise ValueError("the membrane faces must be flat discs with the air face above the water face")
    lo, hi = air[:, :2].min(axis=0), air[:, :2].max(axis=0)
    axis = 0.5 * (lo + hi)
    radius = float(np.hypot(*(air[:, :2] - axis).T).max())
    geometry = []
    for triangles in rigid_triangles:
        centre = triangles.mean(axis=1)
        normal = np.cross(triangles[:, 1] - triangles[:, 0], triangles[:, 2] - triangles[:, 0])
        normal /= np.linalg.norm(normal, axis=1)[:, None]
        geometry.append((triangles, centre, normal))
    lid_z = math.inf
    for _, centre, normal in geometry:
        horizontal = (
            (np.abs(normal[:, 2]) > 0.99)
            & (np.hypot(*(centre[:, :2] - axis).T) < radius)
            & (centre[:, 2] > air_z)
        )
        if horizontal.any():
            lid_z = min(lid_z, float(centre[horizontal, 2].min()))
    if not math.isfinite(lid_z):
        raise ValueError("no rigid lid closes the air chamber above the membrane")
    wall = np.concatenate([
        triangles[(np.abs(normal[:, 2]) < 0.01) & (centre[:, 2] > air_z) & (centre[:, 2] < lid_z)].reshape(-1, 3)
        for triangles, centre, normal in geometry
    ])
    if not wall.size:
        raise ValueError("no rigid wall bounds the air chamber")
    wall_radius = np.hypot(*(wall[:, :2] - axis).T)
    inner_radius, outer_radius = float(wall_radius.min()), float(wall_radius.max())
    if abs(inner_radius - radius) > 1.0e-4:
        raise ValueError(
            f"the air chamber wall (r {inner_radius * 1e3:.3f} mm) does not meet the membrane rim "
            f"(r {radius * 1e3:.3f} mm)"
        )
    return SquidAirChamber(
        axis_xy_m=(float(axis[0]), float(axis[1])),
        inner_radius_m=inner_radius,
        outer_radius_m=outer_radius,
        lid_z_m=lid_z,
        membrane_water_face_z_m=water_z,
        membrane_air_face_z_m=air_z,
        valve_top_z_m=float(valve_triangles.reshape(-1, 3)[:, 2].max()),
    )


