def source_config_shell_anchor_region_ids(
    config: Mapping[str, object],
    fixed_rim_region_id: int,
) -> tuple[int, ...]:
    """Regions whose vertices hold the shell: the fixed rim, and every bonded
    interface whose partner belongs to a rigid (static obstacle) body."""
    analysis = config.get("analysis_settings", {})
    if not isinstance(analysis, Mapping):
        analysis = {}
    faces_of = {
        region_id: set(_face_ids_for_region(dict(config), region_id))
        for pair in analysis.get("solid_part_isolation_allowed_bonded_region_pairs", ()) or ()
        for region_id in (int(pair[0]), int(pair[1]))
    }
    rigid_faces = [
        set(_face_ids_for_region(dict(config), region_id))
        for region_id in _selection_ids_as_int_tuple(
            analysis.get("solid_obstacle_surface_only_region_ids", ())
        )
    ]

    def on_rigid_body(region_id: int) -> bool:
        faces = faces_of[region_id]
        return bool(faces) and any(faces <= rigid for rigid in rigid_faces)

    anchors = {int(fixed_rim_region_id)}
    for pair in analysis.get("solid_part_isolation_allowed_bonded_region_pairs", ()) or ():
        a, b = int(pair[0]), int(pair[1])
        for moving, partner in ((a, b), (b, a)):
            if on_rigid_body(partner) and not on_rigid_body(moving):
                anchors.add(moving)
    return tuple(sorted(anchors))


