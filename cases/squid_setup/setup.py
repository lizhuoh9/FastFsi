def source_config_nozzle_exit_geometry(
    config: Mapping[str, object],
) -> dict[str, object] | None:
    """Exit of the rigid nozzle body that owns the outlet aperture faces.

    Returns None when the source config has no rigid surface obstacle or no
    outlet aperture selection.
    """
    analysis = config.get("analysis_settings", {})
    if not isinstance(analysis, Mapping):
        return None
    obstacle_ids = _selection_ids_as_int_tuple(
        analysis.get("solid_obstacle_surface_only_region_ids", ())
    )
    aperture_faces = set(_face_ids_for_region(dict(config), OUTLET_APERTURE_REGION_ID))
    if not obstacle_ids or not aperture_faces:
        return None
    owners = [
        region_id
        for region_id in obstacle_ids
        if aperture_faces <= set(_face_ids_for_region(dict(config), region_id))
    ]
    if len(owners) != 1:
        raise ValueError(
            f"outlet aperture selection {OUTLET_APERTURE_REGION_ID} must belong to exactly "
            f"one rigid obstacle region; owners {tuple(owners)} among {obstacle_ids}"
        )
    triangles = _region_triangles_m(config, owners)[owners[0]]
    return {"nozzle_body_region_id": int(owners[0]), **nozzle_exit_geometry(triangles)}


