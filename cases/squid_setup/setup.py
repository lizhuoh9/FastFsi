def _growth_bridge_m(fine_m: float, coarse_m: float, growth: float) -> float:
    """Length of the growth-limited cell sequence from one target to another."""
    width, total = min(fine_m, coarse_m), 0.0
    while width * growth < max(fine_m, coarse_m):
        width *= growth
        total += width
    return total + max(fine_m, coarse_m)


